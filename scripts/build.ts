await cp('legacy-public', 'dist/legacy-public', { recursive: true });
await cp('public', 'dist/public', { recursive: true });
await cp('extension', 'dist/extension', { recursive: true });
console.log('Built server and unpacked Chrome extension.');


await build({entryPoints:['src/cloud/server.ts','src/cloud/worker.ts','src/cloud/probe.ts'],outdir:'dist/cloud',platform:'node',format:'esm',packages:'external',bundle:true});

if(cloudOrigin){
 const manifest=JSON.parse(await readFile('extension/manifest.json','utf8'));
 manifest.host_permissions.push(cloudOrigin+'/*');manifest.externally_connectable.matches.push(cloudOrigin+'/*');
 await writeFile('dist/extension/manifest.json',JSON.stringify(manifest,null,2));
}
await cp('public','dist/web',{recursive:true});
await cp('public/byte.html','dist/web/index.html');

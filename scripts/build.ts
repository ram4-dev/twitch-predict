import { build } from 'esbuild';
import { cp, mkdir, writeFile, readFile } from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import { TWITCH_CLIENT_ID, TWITCH_QUERY } from '../src/prediction.js';
const cloudOrigin=process.env.PLOT_PUBLIC_ORIGIN;
if(cloudOrigin){const u=new URL(cloudOrigin);if(u.protocol!=='https:'||u.origin!==cloudOrigin)throw new Error('PLOT_PUBLIC_ORIGIN must be an HTTPS origin');}
await writeFile('extension/app-config.js',`// Generated by npm run build.
export const defaultBridge=${JSON.stringify(cloudOrigin??'http://twitch-predict.localhost:1356')};
export function isAppOrigin(value){try{const u=new URL(value);return ['http:','https:'].includes(u.protocol)&&(['twitch-predict.localhost','twitch-predict-byte.localhost'].includes(u.hostname)||u.origin===${JSON.stringify(cloudOrigin??'http://twitch-predict.localhost:1356')});}catch{return false;}}
`);
await writeFile('extension/twitch.js' , `// Generated by npm run build.\nexport const TWITCH_CLIENT_ID = ${JSON.stringify(TWITCH_CLIENT_ID)};\nexport const TWITCH_QUERY = ${JSON.stringify(TWITCH_QUERY)};\n`);
await build({entryPoints:['src/popup-cache.ts'],outfile:'extension/popup-cache.js',platform:'browser',format:'esm',bundle:true,minify:true});
await build({ entryPoints: ['src/extension-model.ts'], outfile: 'extension/model.js', platform: 'browser', format: 'esm', bundle: true, minify: true });
await build({entryPoints:['src/ui/points-ui.tsx'],outfile:'public/points-ui.js',platform:'browser',format:'esm',bundle:true,minify:true,define:{'process.env.NODE_ENV':'"production"'}});
await build({entryPoints:['src/ui/onboarding.tsx'],outfile:'public/onboarding.js',platform:'browser',format:'esm',bundle:true,minify:true,define:{'process.env.NODE_ENV':'"production"'}});
await build({entryPoints:['src/ui/consoles.tsx'],outfile:'public/consoles.js',platform:'browser',format:'esm',bundle:true,minify:true,define:{'process.env.NODE_ENV':'"production"'}});

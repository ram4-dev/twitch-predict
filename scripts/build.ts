import { build } from 'esbuild';
import { cp, mkdir, writeFile } from 'node:fs/promises';
import { TWITCH_CLIENT_ID, TWITCH_QUERY } from '../src/prediction.js';
await writeFile('extension/twitch.js', `// Generated by npm run build.\nexport const TWITCH_CLIENT_ID = ${JSON.stringify(TWITCH_CLIENT_ID)};\nexport const TWITCH_QUERY = ${JSON.stringify(TWITCH_QUERY)};\n`);
await mkdir('dist', { recursive: true });
await build({ entryPoints: ['src/server.ts'], outfile: 'dist/server.js', platform: 'node', format: 'esm', packages: 'external', bundle: true });
await cp('public', 'dist/public', { recursive: true });
await cp('extension', 'dist/extension', { recursive: true });
console.log('Built server and unpacked Chrome extension.');

import { build } from 'esbuild';
import { cp, mkdir, writeFile } from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import { TWITCH_CLIENT_ID, TWITCH_QUERY } from '../src/prediction.js';
await writeFile('extension/twitch.js', `// Generated by npm run build.\nexport const TWITCH_CLIENT_ID = ${JSON.stringify(TWITCH_CLIENT_ID)};\nexport const TWITCH_QUERY = ${JSON.stringify(TWITCH_QUERY)};\n`);
await build({ entryPoints: ['src/extension-model.ts'], outfile: 'extension/model.js', platform: 'browser', format: 'esm', bundle: true, minify: true });
await build({entryPoints:['src/ui/points-ui.tsx'],outfile:'public/points-ui.js',platform:'browser',format:'esm',bundle:true,minify:true,define:{'process.env.NODE_ENV':'"production"'}});
await build({entryPoints:['src/ui/onboarding.tsx'],outfile:'public/onboarding.js',platform:'browser',format:'esm',bundle:true,minify:true,define:{'process.env.NODE_ENV':'"production"'}});
execFileSync('./node_modules/.bin/tailwindcss',['-i','src/ui/theme.css','-o','public/points-ui.css','--minify'],{stdio:'inherit'});
await cp('public/fonts','extension/fonts',{recursive:true});
await cp('public/points-ui.js', 'extension/points-ui.js');
await cp('public/points-ui.css', 'extension/points-ui.css');
await mkdir('dist', { recursive: true });
await build({ entryPoints: ['src/server.ts'], outfile: 'dist/server.js', platform: 'node', format: 'esm', packages: 'external', bundle: true });
await cp('legacy-public', 'dist/legacy-public', { recursive: true });
await cp('public', 'dist/public', { recursive: true });
await cp('extension', 'dist/extension', { recursive: true });
console.log('Built server and unpacked Chrome extension.');
